"""Command line:

    converter/.venv/bin/python -m converter build     # book -> site/src/generated (idempotent)
    converter/.venv/bin/python -m converter check     # acceptance tests on the generated files
"""
from __future__ import annotations

import json
import sys
from collections import Counter
from pathlib import Path

import yaml

from .config import BOOK, INVENTORY, OUT, OVERRIDES, OWNED_DIRS, OWNED_FILES, RULES
from .tex.nodes import ConvertError


def dump(obj) -> str:
    return json.dumps(obj, ensure_ascii=False, indent=1, sort_keys=True) + "\n"


def write_outputs(files: dict[str, object], out: Path) -> tuple[int, int]:
    written = removed = 0
    out.mkdir(parents=True, exist_ok=True)
    for d in OWNED_DIRS:
        (out / d).mkdir(exist_ok=True)
        for p in sorted((out / d).glob("*.json")):
            if f"{d}/{p.name}" not in files:
                p.unlink()
                removed += 1
    for name, obj in sorted(files.items()):
        top = name.split("/")[0]
        if "/" in name and top not in OWNED_DIRS or "/" not in name and name not in OWNED_FILES:
            raise ConvertError(f"refusing to write {name}: not owned by the converter (config.OWNED_*)")
        p = out / name
        text = dump(obj)
        if not p.exists() or p.read_text() != text:
            p.write_text(text)
            written += 1
    return written, removed


def write_keys_todo(todo: list[dict]) -> None:
    head = ("# Generated by `python -m converter build` -- the answer keys the converter could NOT parse with\n"
            "# certainty. Nothing here is guessed. To resolve one, copy it to overrides/keys.yaml as\n"
            "#   keys:\n#     <id>: {hash: <hash>, key: <structured key>, note: <why>}\n"
            "# (the hash protects against applying a key to a question whose text changed in the book).\n")
    body = yaml.safe_dump({"todo": todo}, sort_keys=False, allow_unicode=True, width=110) if todo else "todo: []\n"
    p = OVERRIDES / "keys-todo.yaml"
    OVERRIDES.mkdir(exist_ok=True)
    text = head + body
    if not p.exists() or p.read_text() != text:
        p.write_text(text)


def build() -> int:
    from .build.book import run
    from .build.output import assemble
    from .check import run_checks

    res = run(BOOK, OVERRIDES)
    files, info = assemble(res, BOOK, RULES, OVERRIDES)
    inventory = json.loads(INVENTORY.read_text())
    R = run_checks(files, inventory)
    stats = {}
    for r in res.chapters:
        stats[r.seg.id] = dict(sorted(r.ctx.stats.items()))
    report = {
        "summary": {
            "chapters": len(res.chapters),
            "lessons": sum(len(r.chapter["lessons"]) for r in res.chapters),
            "chapterQuestions": sum(len(r.drafts) for r in res.chapters),
            "mockQuestions": sum(len(v) for v in res.state.mock_drafts.values()),
            "keysParsed": sum(1 for r in res.chapters for d in r.drafts if d.key_status == "ok")
                          + sum(1 for v in res.state.mock_drafts.values() for d in v if d.key_status == "ok"),
            "keysFlagged": len(info["todo"]),
            "keysOverridden": len(info["overrides"]),
            "figures": sum(len(r.ctx.figures) for r in res.chapters),
            "labs": sum(len(r.ctx.lab_records) for r in res.chapters),
            "traps": len(res.state.traps),
            "glossaryTerms": len(files["glossary.json"]),
            "acceptancePassed": R.ok,
        },
        "acceptance": R.items,
        "flaggedKeys": [{"id": t["id"], "where": t["where"], "format": t["format"], "reason": t["reason"]}
                        for t in info["todo"]],
        "overridesApplied": info["overrides"],
        "bookConsistency": info["problems"],
        "figures": [f for r in res.chapters for f in r.ctx.figures],
        "pathRewrites": {"rules": "converter/rules/paths.yaml", "bookOccurrences": info["pathOccurrences"],
                         "applied": info["rewrites"],
                         "appliedByRule": dict(sorted(Counter(x for a in info["rewrites"] for x in a["rules"]).items()))},
        "warnings": [w for r in res.chapters for w in r.ctx.warnings],
        "stats": stats,
    }
    files["report.json"] = report
    written, removed = write_outputs(files, OUT)
    write_keys_todo(info["todo"])
    print(f"{len(files)} files ({written} changed, {removed} removed) -> {OUT}")
    s = report["summary"]
    print(f"chapters {s['chapters']}, lessons {s['lessons']}, questions {s['chapterQuestions']} + mock "
          f"{s['mockQuestions']}, keys parsed {s['keysParsed']}, flagged {s['keysFlagged']}, figures {s['figures']}, "
          f"labs {s['labs']}, traps {s['traps']}, terms {s['glossaryTerms']}")
    failed = [i for i in R.items if not i["ok"]]
    for i in failed:
        print("FAIL", i["check"], "--", i["detail"][:300])
    if info["problems"]:
        print(f"{len(info['problems'])} book consistency problems (see report.json bookConsistency)")
    print("acceptance:", "ALL PASS" if R.ok else f"{len(failed)} FAILED")
    return 0


def main(argv: list[str]) -> int:
    if len(argv) != 1 or argv[0] not in ("build", "check"):
        print(__doc__)
        return 2
    try:
        if argv[0] == "build":
            return build()
        from .check import main as check_main
        return check_main()
    except ConvertError as e:
        print(f"ERROR: {e}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
