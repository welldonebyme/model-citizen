"""Build the 64 book figures as themable SVGs for the website.

    cd converter/figures && .venv/bin/python build.py            # build everything (PDFs are cached)
    .venv/bin/python build.py --force                             # recompile every PDF
    .venv/bin/python build.py --no-strict                         # allow missing/stale alt texts (warn only)

Writes (all generated, never edit by hand):
    site/src/generated/figures/chNN-figK.svg
    site/src/generated/figures/figures.json   [{id, svg, file, line, sha1, width, height, alt, description?}]
    site/src/generated/figures/figures.css    light/dark values of every --fig-* token
    converter/figures/COLORS.md               the colour -> token mapping actually used
Reads: ../dbt-bible (read only), converter/overrides/figures.yaml (alt texts, keyed by id + sha1).
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import yaml

import colors
import figsrc
import svgpost
import texbuild

ACADEMY = figsrc.ACADEMY
OUT = ACADEMY / "site/src/generated/figures"
OVERRIDES = ACADEMY / "converter/overrides/figures.yaml"
INVENTORY = ACADEMY / "reference/content-inventory.json"
COLORS_MD = figsrc.HERE / "COLORS.md"


def check_counts(figs) -> None:
    inv = json.loads(INVENTORY.read_text())
    want = {c["number"]: c["tikz"] for c in inv["chapters"]}
    got: dict[int, int] = {}
    for f in figs:
        got[f.chapter] = got.get(f.chapter, 0) + 1
    bad = {n: (want.get(n, 0), got.get(n, 0)) for n in set(want) | set(got) if want.get(n, 0) != got.get(n, 0)}
    if bad or len(figs) != inv["summary"]["tikz_figures_total"]:
        raise SystemExit(f"figure count differs from reference/content-inventory.json: {bad} (total {len(figs)})")


def load_alts(figs, strict: bool) -> dict[str, dict]:
    data = yaml.safe_load(OVERRIDES.read_text()) if OVERRIDES.exists() else {}
    data = data or {}
    problems = []
    ids = {f.id for f in figs}
    for f in figs:
        e = data.get(f.id)
        if not e or not e.get("alt"):
            problems.append(f"{f.id}: no alt text in converter/overrides/figures.yaml")
        elif e.get("sha1") != f.sha1:
            problems.append(f"{f.id}: stale alt text (sha1 {e.get('sha1')} != source {f.sha1}); "
                            f"re-check the alt text against {f.file}:{f.line} and update the sha1")
    for k in data:
        if k not in ids:
            problems.append(f"{k}: alt text for a figure that no longer exists")
    if problems:
        msg = "\n".join(problems)
        if strict:
            raise SystemExit("alt text problems:\n" + msg)
        print("WARNING alt text problems:\n" + msg, file=sys.stderr)
    return {k: v for k, v in data.items() if v and v.get("sha1") == next((f.sha1 for f in figs if f.id == k), None)}


def css(mapper: colors.Mapper) -> str:
    toks = sorted(mapper.used)
    base_tokens = {
        "--fig-font-sans": "'Fira Sans', 'Helvetica Neue', Arial, sans-serif",
        "--fig-font-mono": "'Fira Mono', Menlo, Consolas, monospace",
        "--fig-font-serif": "'TeX Gyre Pagella', Palatino, 'Palatino Linotype', 'Book Antiqua', serif",
        "--fig-font-math": "'Fira Sans', 'STIX Two Math', 'Cambria Math', 'Segoe UI Symbol', 'Apple Symbols', "
                           "'DejaVu Sans', sans-serif",
    }
    light = [f"  {t}: {mapper.used[t]['light']};" for t in toks]
    dark = [f"  {t}: {mapper.used[t]['dark']};" for t in toks]
    fonts = [f"  {k}: {v};" for k, v in base_tokens.items()]
    return "\n".join([
        "/* generated by converter/figures/build.py -- do not edit.",
        "   Colour tokens of the book figures (inline the SVGs so these apply). The SVGs carry the light",
        "   values as fallbacks; see converter/figures/COLORS.md for the mapping. */",
        ":root {", *fonts, *light, "}",
        "@media (prefers-color-scheme: dark) {", "  :root:not([data-theme=\"light\"]) {",
        *["  " + l for l in dark], "  }", "}",
        ":root[data-theme=\"dark\"] {", *dark, "}", "",
    ])


def colors_md(mapper: colors.Mapper, figs) -> str:
    order = {f.id: i for i, f in enumerate(figs)}
    rows = []
    for t in sorted(mapper.used, key=lambda t: (mapper.used[t]["expr"].split("!")[0], t)):
        u = mapper.used[t]
        fl = sorted(u["figures"], key=order.get)
        shown = ", ".join(fl[:6]) + (f" … (+{len(fl) - 6})" if len(fl) > 6 else "")
        hexes = ", ".join(sorted(h.lower() for h in u["hex"]))
        rows.append(f"| `{t}` | `{u['expr']}` | {hexes} | `{u['light']}` | `{u['dark']}` | {len(fl)} | {shown} |")
    unmatched = "".join(f"- `{h}` in {', '.join(sorted(v))}\n" for h, v in sorted(mapper.unmatched.items())) or "none\n"
    base = "\n".join(f"| `{k}` | `{v}` |" for k, v in colors.DARK_BASE.items())
    return f"""# Figure colours → CSS custom properties

Generated by `build.py` (do not edit by hand; edit `colors.py` and re-run). Every colour present in the 64 SVGs
was traced back to the xcolor expression of the book that produced it and replaced by
`var(--fig-…, #light)`. The light value is the exact book colour (sRGB, as xcolor computes it); the SVG
keeps it as fallback, so an SVG used through `<img>` (no CSS variables) still looks like the book.
`site/src/generated/figures/figures.css` defines every token for light and dark mode
(`prefers-color-scheme`, overridable with `data-theme="light|dark"` on `<html>`).

## Rules

- Book palette (`preamble.tex`): `ink #1F2A44`, `accent #E8573F`, `muted #6B7280`, `codebg #F6F7F9`,
  `codeframe #D7DBE2`, `outbg #FBFBF5`, `whyC #2563EB`, `ideaC #D97706`, `labC #059669`, `trapC #DC2626`,
  `tipC #0891B2`, `quizC #7C3AED` (`examC` = ink, `deepC` = muted).
- `white` as a **shape fill** is the paper → `--fig-paper`; `white` as **text** (labels on solid badges) →
  `--fig-on-solid`; `black` (TeX's default text colour, also set on the root `<svg>`) → `--fig-text`.
- `x!p` (p % of x on white) → `--fig-<x>-<p>`; `x!p!y` → `--fig-<x>-<p>-<y>`; e.g. `accent!12` →
  `--fig-accent-12`, `labC!80!black` → `--fig-lab-80-black`, `ink!70` → `--fig-ink-70`.
- **Dark mode**: each expression is re-evaluated with the dark base palette below. Since white = paper and
  black = text, tints (`accent!12`) become dark tints of a lighter accent, shades (`x!80!black`) become
  lighter, and `ink` (text/lines) becomes light. Solid badges (`fill=accent`, `fill=ink` + white text) keep
  readable contrast because their white text becomes `--fig-on-solid` = dark paper.
- Hand overrides for dark mode (only the two dbt-docs-like node colours of ch20-fig2, whose computed dark
  value would make their text hard to read): {", ".join(f"`{k}` → `{v}`" for k, v in colors.DARK_OVERRIDE.items())}.
- `yellow` is a CMYK colour in xcolor; MuPDF converts `yellow!70!orange` = cmyk(0,.15,1,0) to `#FFD401`, which
  is matched explicitly (`colors.PDF_ALIASES`); the token's light value is the RGB evaluation `#FFD900`.
- White is also used to *erase* (ch04-fig2 "left anti", ch04-fig5 EXCEPT paint a white circle over a filled
  one). In dark mode these areas show `--fig-paper`, so `--fig-paper` should equal the background the
  figure sits on (set it on the figure container if the site's card colour differs from `#141A24`).
- Fonts are CSS variables too: `--fig-font-sans` (Fira Sans: root default), `--fig-font-mono` (Fira Mono),
  `--fig-font-serif` (TeX Gyre Pagella, one note in ch04-fig1), `--fig-font-math` (math symbols →, ⟵, ⟶, −, >).
- The variables only apply to SVGs **inlined** in the HTML; through `<img>` the light fallbacks are used.
- Contrast (re-check with `contrast.py`: every text span against the shape under it). Last check: dark mode ≥ 4.69:1; light
  mode keeps the book's own colours, whose lowest pairs are 3.19–4.2:1 (white on `accent`/`labC`/`ideaC`
  badges, `accent`/`labC`/`ink!60` text on white), none below 3:1.
- Unmatched colours (would be `--fig-x-<hex>`): {unmatched}
## Dark base palette

| book colour | dark value |
|---|---|
{base}

## Every token used ({len(mapper.used)})

| token | book expression | hex found in PDF | light | dark | figures | where |
|---|---|---|---|---|---|---|
""" + "\n".join(rows) + "\n"


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--force", action="store_true", help="recompile all PDFs")
    ap.add_argument("--no-strict", action="store_true", help="warn instead of failing on alt-text problems")
    args = ap.parse_args(argv)

    figs = figsrc.figures()
    check_counts(figs)
    alts = load_alts(figs, strict=not args.no_strict)
    pdfs = texbuild.compile_all(figs, force=args.force)

    OUT.mkdir(parents=True, exist_ok=True)
    mapper = colors.Mapper()
    meta = []
    total = 0
    for f in figs:
        cands = mapper.candidates(f.source + "\n".join(texbuild.chapter_prelude(f)))
        raw = svgpost.pdf_to_svg_text(pdfs[f.id])
        a = alts.get(f.id, {})
        svg, w, h, stats = svgpost.postprocess(raw, f.id, mapper, cands, title=a.get("alt"))
        path = OUT / f"{f.id}.svg"
        if not path.exists() or path.read_text() != svg:
            path.write_text(svg)
        total += len(svg.encode())
        entry = {"id": f.id, "svg": f"{f.id}.svg", "file": f.file, "line": f.line, "sha1": f.sha1,
                 "width": w, "height": h, "alt": a.get("alt", "")}
        if a.get("description"):
            entry["description"] = " ".join(a["description"].split())
        meta.append(entry)
    # remove SVGs of figures that no longer exist
    keep = {f"{f.id}.svg" for f in figs}
    for p in OUT.glob("ch*-fig*.svg"):
        if p.name not in keep:
            p.unlink()
    files = {
        OUT / "figures.json": json.dumps(meta, indent=2, ensure_ascii=False) + "\n",
        OUT / "figures.css": css(mapper),
        COLORS_MD: colors_md(mapper, figs),
    }
    for p, content in files.items():
        if not p.exists() or p.read_text() != content:
            p.write_text(content)
    print(f"{len(figs)} figures -> {OUT.relative_to(ACADEMY)} ({total / 1024:.0f} KiB of SVG), "
          f"{len(mapper.used)} colour tokens, unmatched colours: {sorted(mapper.unmatched) or 'none'}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
