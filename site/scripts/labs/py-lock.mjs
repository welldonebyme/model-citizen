#!/usr/bin/env node
// Lock file of the YAML / Jinja playgrounds (src/lib/py/pyodide-lock.labs.json).
//
// The Pyodide core and the wheels are NOT ours: they live in the shared folder public/engines/pyodide/<version>/,
// built by the dbt terminal's script (scripts/dbt/build-engine.mjs, sources pinned in scripts/dbt/engine-sources.json).
// The playgrounds only need 3 of those wheels, so they load Pyodide from that folder (indexURL) with this small
// lock (3 packages, ~1 KB, passed as `lockFileContents`) instead of the folder's lock.
//
//   node scripts/labs/py-lock.mjs           write the lock from engine-sources.json, then check the shared folder
//   node scripts/labs/py-lock.mjs --check   only check (exit 1 if the lock is stale or a file is missing/different)
//
// If the shared folder does not exist yet, build it with: node scripts/dbt/build-engine.mjs (same file names).
import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const SITE = path.resolve(HERE, '..', '..');
const SOURCES = JSON.parse(fs.readFileSync(path.join(SITE, 'scripts', 'dbt', 'engine-sources.json'), 'utf8'));
const OUT = path.join(SITE, 'src', 'lib', 'py', 'pyodide-lock.labs.json');
const WANT = ['jinja2', 'markupsafe', 'pyyaml'];
const CHECK = process.argv.includes('--check');
const log = (...a) => console.log('[labs:py-lock]', ...a);

const version = SOURCES.versions.pyodide;
const packages = {};
for (const name of WANT) {
  const p = SOURCES.packages.find((x) => x.name === name);
  if (!p) throw new Error(`${name} is not in engine-sources.json`);
  if (!p.shared || p.derive) throw new Error(`${name} must be a shared, non-derived wheel`);
  packages[name] = { ...p.lock, file_name: p.file, sha256: p.source.sha256 };
}
const lock = {
  $comment: 'Generated by scripts/labs/py-lock.mjs from scripts/dbt/engine-sources.json. Files are served from <base>engines/pyodide/' + version + '/.',
  pyodideVersion: version,
  info: SOURCES.lockInfo,
  packages,
};
const text = JSON.stringify(lock, null, 1) + '\n';
const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : null;
if (current !== text) {
  if (CHECK) { console.error('[labs:py-lock] the lock is stale: run node scripts/labs/py-lock.mjs'); process.exit(1); }
  fs.writeFileSync(OUT, text);
  log('wrote', path.relative(SITE, OUT));
}

const dir = path.join(SITE, 'public', 'engines', 'pyodide', version);
if (!fs.existsSync(dir)) {
  console.error(`[labs:py-lock] ${path.relative(SITE, dir)} does not exist: build it with  node scripts/dbt/build-engine.mjs`);
  process.exit(CHECK ? 1 : 0);
}
let bad = 0;
const need = [...SOURCES.core.map((c) => ({ file: c.file, sha256: c.sha256 })), ...Object.values(packages).map((p) => ({ file: p.file_name, sha256: p.sha256 }))];
for (const f of need) {
  const p = path.join(dir, f.file);
  if (!fs.existsSync(p)) { console.error('[labs:py-lock] missing', f.file); bad++; continue; }
  const got = crypto.createHash('sha256').update(fs.readFileSync(p)).digest('hex');
  if (got !== f.sha256) { console.error('[labs:py-lock] sha256 differs', f.file); bad++; }
}
if (bad) process.exit(1);
log(`shared Pyodide ${version} folder OK (${need.length} files checked)`);
